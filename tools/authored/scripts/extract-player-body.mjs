#!/usr/bin/env node
/**
 * Extracts the player body proxy that the wearable generators fit to.
 *
 * Wearables must fit `char_player_a` exactly and deform with it, so they are shaped against its
 * real bind-pose surface and borrow its skin weights. This script samples the published player GLB
 * (LOD0 head, body, trousers and feet) in a headless page and writes
 * `tools/authored/generators/wearables/playerBody.json`: bone bind positions, and per vertex its
 * position (mm), normal, region tag and three strongest bone weights. Re-run it whenever the player
 * model changes, then regenerate the wearables.
 *
 * Usage: node tools/authored/scripts/extract-player-body.mjs
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";
import { chromium } from "playwright";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const SOURCE = "public/assets/models/char_player_a.glb";
const OUTPUT = "tools/authored/generators/wearables/playerBody.json";

const bundle = await build({
  entryPoints: [path.join(ROOT, "tools/authored/scripts/extract-player-body-entry.ts")],
  bundle: true, format: "iife", platform: "browser", write: false, logLevel: "warning"
});
const bytes = await readFile(path.join(ROOT, SOURCE));
const browser = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
try {
  const page = await browser.newPage();
  await page.setContent("<!doctype html><html><body></body></html>");
  await page.addScriptTag({ content: bundle.outputFiles[0].text });
  const body = await page.evaluate((b64) => window.extractPlayerBody(b64), bytes.toString("base64"));
  const document = {
    source: SOURCE,
    sourceSha256: createHash("sha256").update(bytes).digest("hex"),
    note: "Generated by tools/authored/scripts/extract-player-body.mjs; positions in mm, normals x127, weights x255.",
    ...body
  };
  await writeFile(path.join(ROOT, OUTPUT), `${JSON.stringify(document)}\n`);
  console.info(`[player body] ${body.positions.length / 3} vertices, ${body.bones.length} bones, tags ${body.tags.join(", ")}`);
} finally {
  await browser.close();
}
